"""
Prometheus routes: file/zip export, HTTP service discovery, and live status
"""
import hmac
import os
from collections import Counter

from flask import Blueprint, Response, jsonify, request
from sqlalchemy.orm import selectinload

from config import Config
from models import Device
from services.prometheus_service import (
    build_http_sd,
    export_to_disk,
    export_to_zip,
    iter_enabled_targets,
)
from services import prometheus_status

prometheus_bp = Blueprint('prometheus', __name__)

# Groups probed through an exporter's /probe endpoint rather than scraped directly
BLACKBOX_MODULES = {'icmp': 'icmp', 'http': 'http_2xx', 'https': 'http_2xx', 'dns': 'dns'}


def register_prometheus_routes(app, limiter):
    """Register Prometheus routes with the app"""
    app.register_blueprint(prometheus_bp, url_prefix='/api/prometheus')

    # Apply rate limiting
    limiter.limit("10 per minute")(export_prometheus_config)
    # Prometheus polls SD on refresh_interval per job; leave generous headroom
    limiter.limit("600 per minute")(http_service_discovery)
    limiter.limit("120 per minute")(get_status)


def _monitored_devices():
    return (Device.query
            .options(selectinload(Device.monitors))
            .filter_by(monitoring_enabled=True)
            .all())


def _sd_token():
    return os.environ.get('PROMETHEUS_SD_TOKEN') or None


def _sd_authorized():
    token = _sd_token()
    if not token:
        return True
    header = request.headers.get('Authorization', '')
    supplied = header[7:] if header.startswith('Bearer ') else ''
    return hmac.compare_digest(supplied.encode(), token.encode())


@prometheus_bp.route('/export', methods=['GET'])
def export_prometheus_config():
    """Export Prometheus configuration"""
    devices = _monitored_devices()

    export_mode = request.args.get('mode', 'write')
    export_path = os.environ.get('PROMETHEUS_EXPORT_PATH', Config.PROMETHEUS_EXPORT_PATH)

    if export_mode == 'write':
        result = export_to_disk(export_path, devices)
        return jsonify(result)
    else:  # download mode
        return export_to_zip(devices)


@prometheus_bp.route('/sd', methods=['GET'])
def http_service_discovery():
    """
    Prometheus HTTP service discovery (http_sd_configs).
    Optional ?group=<name> limits the result to one export group, e.g.
    linux_node_exporter, snmp, icmp. Always returns 200 with a JSON list.
    """
    if not _sd_authorized():
        return jsonify({'error': 'Unauthorized'}), 401
    group = request.args.get('group') or None
    payload = build_http_sd(_monitored_devices(), group=group)
    return jsonify(payload)


@prometheus_bp.route('/sd/groups', methods=['GET'])
def http_service_discovery_groups():
    """Groups that currently have targets, with counts"""
    counts = Counter(group for _d, _m, group, _t in iter_enabled_targets(_monitored_devices()))
    return jsonify([{'group': g, 'targets': n} for g, n in sorted(counts.items())])


def _scrape_config_yaml(base_url, groups, blackbox, snmp_exporter, token_set):
    lines = [
        '# Generated by Homelab Inventory. Paste under `scrape_configs:` in prometheus.yml.',
        '# Targets update automatically; no file export or reload needed.',
        '',
    ]
    auth = []
    if token_set:
        auth = [
            '      authorization:',
            '        credentials: <PROMETHEUS_SD_TOKEN>',
        ]
    for group in groups:
        lines += [
            f'- job_name: inventory_{group}',
        ]
        if group in BLACKBOX_MODULES:
            lines += [
                '  metrics_path: /probe',
                '  params:',
                f'    module: [{BLACKBOX_MODULES[group]}]',
            ]
        elif group == 'snmp':
            lines += [
                '  metrics_path: /snmp',
                '  params:',
                '    module: [if_mib]',
            ]
        lines += [
            '  http_sd_configs:',
            f'    - url: {base_url}/api/prometheus/sd?group={group}',
            '      refresh_interval: 60s',
        ] + auth

        if group in BLACKBOX_MODULES or group == 'snmp':
            exporter = blackbox if group in BLACKBOX_MODULES else snmp_exporter
            lines += [
                '  relabel_configs:',
                '    - source_labels: [__address__]',
                '      target_label: __param_target',
                '    - source_labels: [__param_target]',
                '      target_label: instance',
                '    - target_label: __address__',
                f'      replacement: {exporter}',
            ]
        elif group in ('ipmi', 'nut'):
            lines.append(f'  # {group}: if you use a multi-target exporter, add /probe-style relabeling here')
        lines.append('')
    return '\n'.join(lines)


@prometheus_bp.route('/sd/scrape-config', methods=['GET'])
def http_service_discovery_scrape_config():
    """
    A ready-to-paste scrape_configs snippet using http_sd_configs.
    Query params:
      base_url        - how Prometheus reaches this app (default: request host)
      blackbox        - blackbox exporter address (default blackbox-exporter:9115)
      snmp_exporter   - snmp exporter address (default snmp-exporter:9116)
      all=true        - include every known group, not only groups with targets
    """
    base_url = (request.args.get('base_url') or request.host_url).rstrip('/')
    blackbox = request.args.get('blackbox') or 'blackbox-exporter:9115'
    snmp_exporter = request.args.get('snmp_exporter') or 'snmp-exporter:9116'
    if request.args.get('all', '').lower() in ('1', 'true', 'yes'):
        groups = sorted({'linux_node_exporter', 'freebsd_node_exporter', 'node_exporter',
                         'smartctl_exporter', 'snmp', 'icmp', 'http', 'https', 'dns',
                         'ipmi', 'nut', 'docker'})
    else:
        groups = sorted({g for _d, _m, g, _t in iter_enabled_targets(_monitored_devices())})
    body = _scrape_config_yaml(base_url, groups, blackbox, snmp_exporter, bool(_sd_token()))
    return Response(body, mimetype='text/yaml')


@prometheus_bp.route('/status', methods=['GET'])
def get_status():
    """
    Live per-device status from PROMETHEUS_URL.
    Always 200; `enabled=false` when Prometheus isn't configured and
    `error` set when it can't be reached, so the UI can degrade quietly.
    """
    if not prometheus_status.is_configured():
        return jsonify({'enabled': False, 'error': None, 'summary': None, 'devices': {}})

    force = request.args.get('refresh', '').lower() in ('1', 'true', 'yes')
    series, error = prometheus_status.fetch_series(force=force)
    if error:
        return jsonify({'enabled': True, 'error': error, 'summary': None, 'devices': {}})

    devices = Device.query.options(selectinload(Device.monitors)).all()
    status = prometheus_status.compute_status(devices, series)
    return jsonify({
        'enabled': True,
        'error': None,
        'summary': prometheus_status.summarize(status),
        'devices': {str(k): v for k, v in status.items()},
    })
